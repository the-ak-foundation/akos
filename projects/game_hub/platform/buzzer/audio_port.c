/**
 ******************************************************************************
 * @file    audio_port.c
 * @brief   Protect shared audio playback from concurrent task access
 *
 * @module  Game Hub - Buzzer
 ******************************************************************************
 */

/*==================================================================================================
*                                          INCLUDE FILES
==================================================================================================*/
#include "audio_port.h"

#include "stm32l1xx.h"

/*==================================================================================================
*                                         GLOBAL FUNCTIONS
==================================================================================================*/
uint32_t audio_port_lock(void) {
    uint32_t state = __get_PRIMASK();

    __disable_irq();
    return state;
}

void audio_port_unlock(uint32_t state) {
    __set_PRIMASK(state);
}
