/*==================================================================================================
*                                          INCLUDE FILES
==================================================================================================*/
#include "system.h"

#include "uart.h"
#include "stm32l1xx.h"
#include "xprintf.h"

/*==================================================================================================
*                                        PRIVATE FUNCTIONS
==================================================================================================*/
static void system_console_putc(int character) {
    uart_putc((char)character);
}

/*==================================================================================================
*                                         GLOBAL FUNCTIONS
==================================================================================================*/
void system_init_console(void) {
    xdev_out(system_console_putc);
}

void SysInitConsole(void) {
    system_init_console();
}

void system_reboot(void) {
    uart_flush();
    NVIC_SystemReset();
}
