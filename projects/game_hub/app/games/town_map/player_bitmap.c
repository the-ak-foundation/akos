const uint8_t *player_get_bitmap(PlayerDirection direction, PlayerFrame frame) {
    if ((direction >= PLAYER_DIR_COUNT) || (frame >= PLAYER_FRAME_COUNT)) {
        return g_player_bitmap[PLAYER_SPRITE_DOWN_0];
    }

    return g_player_bitmap[PLAYER_SPRITE_INDEX(direction, frame)];
}
